export const DEPLOYMENT_RECORD_SCHEMA_VERSION = 1;

export type RecordedDeployment = {
  deploymentId: string;
  sha: string;
  environment: "production" | "preview";
  host: string;
  state: string;
  createdAt: string;
  /** What verified this deployment, e.g. a receipt file or the smoke workflow. */
  verified: string | null;
};

export type DeploymentRecordFile = {
  schemaVersion: number;
  note: string;
  deployments: RecordedDeployment[];
};

export type VercelDeploymentInput = {
  uid: string;
  url: string;
  readyState: string;
  target: string | null;
  createdAt: number;
  alias?: readonly string[];
  meta?: {
    githubCommitSha?: string;
    githubCommitRef?: string;
  };
};

export const DEPLOYMENT_RECORD_NOTE =
  "Append-only production deployment record. Generated by `node --experimental-strip-types scripts/record-deployment.ts`; the `verified` field is preserved across runs. See docs/runbooks/releases.md.";

export function toRecordedDeployment(input: VercelDeploymentInput): RecordedDeployment {
  const isProduction = input.target === "production";
  return {
    deploymentId: input.uid,
    sha: input.meta?.githubCommitSha?.trim() || "unknown",
    environment: isProduction ? "production" : "preview",
    // A production listing carries a per-deployment host, not the alias. The
    // record is about what users reach, so production entries use the alias.
    host: `https://${input.alias?.[0] ?? (isProduction ? "kossilon-hub.vercel.app" : input.url)}`,
    state: input.readyState,
    createdAt: new Date(input.createdAt).toISOString(),
    verified: null,
  };
}

/**
 * Merge a fresh Vercel listing into the checked-in record.
 *
 * Verification is manual knowledge (a receipt, a smoke run, a rollback drill);
 * refreshing the listing must not erase it. Everything else is platform fact and
 * wins over what is in the file.
 */
export function mergeDeploymentRecords(
  existing: readonly RecordedDeployment[],
  fetched: readonly RecordedDeployment[],
  limit = 40,
): RecordedDeployment[] {
  const verifiedById = new Map(
    existing
      .filter((record) => record.verified)
      .map((record) => [record.deploymentId, record.verified]),
  );

  const byId = new Map<string, RecordedDeployment>();
  for (const record of fetched) {
    byId.set(record.deploymentId, {
      ...record,
      verified: verifiedById.get(record.deploymentId) ?? record.verified,
    });
  }
  for (const record of existing) {
    if (!byId.has(record.deploymentId)) byId.set(record.deploymentId, record);
  }

  return [...byId.values()]
    .sort((left, right) => Date.parse(right.createdAt) - Date.parse(left.createdAt))
    .slice(0, limit);
}
